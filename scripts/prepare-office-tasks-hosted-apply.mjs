import { createHash } from 'node:crypto';
import { OFFICE_TASKS_PREREQUISITE_HISTORY } from './office-tasks-production-history.mjs';
import { constants, closeSync, fstatSync, openSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OFFICE_TASKS_VERSION = '20260821141530';
const OFFICE_TASKS_FILENAME = '20260821141530_office_tasks.sql';
const OFFICE_TASKS_SHA256 = 'dc53110c349f4864725531adb9295707a6d5140c037885f1863d58a8be1347a2';
const MIGRATION_PATH = fileURLToPath(new URL(`../supabase/migrations/${OFFICE_TASKS_FILENAME}`, import.meta.url));

function sqlTextLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

const PREREQUISITE_HISTORY_VALUES = OFFICE_TASKS_PREREQUISITE_HISTORY
  .map(row => `(${sqlTextLiteral(row.version)}, ${sqlTextLiteral(row.name)})`)
  .join(',\n      ');

function readExactOfficeTasksMigration(path = MIGRATION_PATH) {
  let descriptor;
  try {
    descriptor = openSync(path, constants.O_RDONLY | constants.O_NOFOLLOW);
    if (!fstatSync(descriptor).isFile()) throw new Error('not a file');
    const sql = readFileSync(descriptor);
    const sha256 = createHash('sha256').update(sql).digest('hex');
    if (sha256 !== OFFICE_TASKS_SHA256) throw new Error('Office Tasks migration SHA-256 no longer matches review');
    const text = sql.toString('utf8');
    if (!Buffer.from(text, 'utf8').equals(sql) || !text.endsWith('\n')) {
      throw new Error('Office Tasks migration must be UTF-8 and end with a newline');
    }
    if (/^\s*(?:begin|start\s+transaction|commit|rollback)\s*;/im.test(text)) {
      throw new Error('Office Tasks migration must not contain transaction control');
    }
    return text;
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
  }
}

function buildOfficeTasksDriver(migration = readExactOfficeTasksMigration()) {
  return `\\set ON_ERROR_STOP on
-- Generated by scripts/prepare-office-tasks-hosted-apply.mjs.
-- Applies only the reviewed Office Tasks migration. Migration history is repaired separately.
begin;

do $office_tasks_preflight$
begin
  if (
    select count(*) from supabase_migrations.schema_migrations
  ) <> ${OFFICE_TASKS_PREREQUISITE_HISTORY.length}
    or exists (
      select 1
      from supabase_migrations.schema_migrations as actual
      where (actual.version, actual.name) not in (values
      ${PREREQUISITE_HISTORY_VALUES}
      )
    ) then
    raise exception 'Office Tasks migration history is not in the reviewed pre-apply state';
  end if;
  if to_regclass('public.ops_tasks') is not null
    or to_regclass('public.ops_task_events') is not null
    or to_regprocedure('public.ops_create_manual_task(text,text,timestamp with time zone,uuid,uuid)') is not null
    or to_regprocedure('public.ops_update_own_task(uuid,text,text,uuid,uuid)') is not null then
    raise exception 'Office Tasks schema is not absent before apply';
  end if;
end
$office_tasks_preflight$;

-- BEGIN canonical migration ${OFFICE_TASKS_VERSION}: ${OFFICE_TASKS_FILENAME}
${migration}-- END canonical migration ${OFFICE_TASKS_VERSION}: ${OFFICE_TASKS_FILENAME}

do $office_tasks_postcondition$
begin
  if to_regclass('public.ops_tasks') is null
    or to_regclass('public.ops_task_events') is null
    or to_regprocedure('public.ops_create_manual_task(text,text,timestamp with time zone,uuid,uuid)') is null
    or to_regprocedure('public.ops_update_own_task(uuid,text,text,uuid,uuid)') is null
    or not exists (
      select 1 from pg_class
      where oid = 'public.ops_tasks'::regclass and relrowsecurity and relforcerowsecurity
    )
    or not exists (
      select 1 from pg_class
      where oid = 'public.ops_task_events'::regclass and relrowsecurity and relforcerowsecurity
    )
    or exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename in ('ops_tasks', 'ops_task_events')
    ) then
    raise exception 'Office Tasks postcondition failed';
  end if;
end
$office_tasks_postcondition$;

commit;
`;
}

function assertGeneratedOfficeTasksDriver(value) {
  const bytes = Buffer.isBuffer(value) ? value : Buffer.from(value);
  const text = bytes.toString('utf8');
  if (!Buffer.from(text, 'utf8').equals(bytes) || !Buffer.from(buildOfficeTasksDriver(), 'utf8').equals(bytes)) {
    throw new Error('apply input is not the exact generated Office Tasks driver');
  }
}

function main(args = process.argv.slice(2)) {
  if (args.length !== 2 || args[0] !== '--output' || !args[1]) {
    throw new Error('Usage: node scripts/prepare-office-tasks-hosted-apply.mjs --output FILE');
  }
  const driver = buildOfficeTasksDriver();
  writeFileSync(args[1], driver, { flag: 'wx', mode: 0o600 });
  process.stderr.write(`wrote ${args[1]} (driver SHA-256 ${createHash('sha256').update(driver).digest('hex')})\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try { main(); } catch (error) { process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`); process.exitCode = 1; }
}

export { OFFICE_TASKS_FILENAME, OFFICE_TASKS_SHA256, OFFICE_TASKS_VERSION, PREREQUISITE_HISTORY_VALUES, assertGeneratedOfficeTasksDriver, buildOfficeTasksDriver, readExactOfficeTasksMigration };
